open Lexer
open Types

let read_file path =
    let ic = open_in path in
    really_input_string ic (in_channel_length ic)

let int_to_reg n =
  match n with
  | 0 -> R0 | 1 -> R1 | 2 -> R2 | 3 -> R3
  | 4 -> R4 | 5 -> R5 | 6 -> R6 | 7 -> R7
  | 8 -> R8 | 9 -> R9 | 10 -> R10 | 11 -> R11
  | 12 -> R12 | 13 -> R13 | 14 -> R14 | 15 -> R15
  | _ -> failwith ("Invalid register number: " ^ string_of_int n)

let lex_string s =
    let lexbuf = Lexing.from_string s in
    let rec aux () =
        match Lexer.token lexbuf with
        | EOF -> []
        | tok -> tok :: aux ()
    in
    aux ()

let parse_inst_from_toks = function
  | LLI :: REG rd :: IMM imm :: ts ->
      (Lli (int_to_reg rd, imm), ts)
  | LUI :: REG rd :: IMM imm :: ts ->
      (Lui (int_to_reg rd, imm), ts)
  | LD :: REG rd :: REG rs :: IMM imm :: ts ->
      (Ld (int_to_reg rd, int_to_reg rs, imm), ts)
  | ST :: REG rs1 :: REG rs2 :: IMM imm :: ts ->
      (St (int_to_reg rs1, int_to_reg rs2, imm), ts)
  | ADD :: REG rd :: REG rs1 :: REG rs2 :: ts ->
      (Add (int_to_reg rd, int_to_reg rs1, int_to_reg rs2), ts)
  | ADDI :: REG rd :: REG rs :: IMM imm :: ts ->
      (Addi (int_to_reg rd, int_to_reg rs, imm), ts)
  | SUB :: REG rd :: REG rs1 :: REG rs2 :: ts ->
      (Sub (int_to_reg rd, int_to_reg rs1, int_to_reg rs2), ts)
  | AND :: REG rd :: REG rs1 :: REG rs2 :: ts ->
      (And (int_to_reg rd, int_to_reg rs1, int_to_reg rs2), ts)
  | NOT :: REG rd :: REG rs :: ts ->
      (Not (int_to_reg rd, int_to_reg rs), ts)
  | BEQ :: REG rs1 :: REG rs2 :: LABEL lbl :: ts ->
      (Beq (int_to_reg rs1, int_to_reg rs2, lbl), ts)
  | BLT :: REG rs1 :: REG rs2 :: LABEL lbl :: ts ->
      (Blt (int_to_reg rs1, int_to_reg rs2, lbl), ts)
  | JALR :: REG rd :: REG rs :: IMM imm :: ts ->
      (Jalr (int_to_reg rd, int_to_reg rs, imm), ts)
  | APC :: REG rd :: IMM imm :: ts ->
      (Apc (int_to_reg rd, imm), ts)
  | J :: LABEL lbl :: ts ->
      (J lbl, ts)
  | LABEL lbl :: ts ->
      (Label lbl, ts)
  | SPIN :: ts ->
      (Spin, ts)
  | _ ->
      failwith "Parsing error: Invalid syntax."


let rec parse_prog_from_toks toks =
  match toks with
  | [] -> []
  | [EOF] -> []
  | NEWLINE :: ts -> parse_prog_from_toks ts
  | _ ->
      let (inst, ts) = parse_inst_from_toks toks in
      inst :: parse_prog_from_toks ts

let parse_prog s =
  parse_prog_from_toks (lex_string s)

let parse_prog_from_path path =
    parse_prog (read_file path)

