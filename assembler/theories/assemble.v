Open Scope string_scope.
Open Scope list_scope.


(** [inst_width ins] returns how many ISA instructions the ASM instruction
    [ins] will correspond to. *)
Definition inst_width {L A:Type} (ins:@asm.annot_inst L A) : nat :=
    match asm.inst_of_annot_inst ins with
    | asm.Label _ => 0
    | _           => 1
    end.


(** A symbol table here is [symtable.t] with bindings of value [nat * A]. A
    binding [s -> (n, a)] in the symbol table denotes that the string [s]
    corresponds to line number [n], the instruction at which line has the
    annotation [a]. *)
Definition table (A:Type) : Type := symtable.t (nat * A).

(** [empty_table] is an empty symbol table. *)
Definition empty_table {A:Type} : table A := symtable.empty _.


(** [build_symtable n m p] returns a symtable with bindings from [m], and
    additionally bindings from annotated program with string labels [p],
    assuming the first line number to be [n].
    NOTE: The label type is enforced to be a string here! *)
Fixpoint build_symtable {A:Type} (n:nat) (m:table A) (p:@asm.annot_prog string A)
    : table A :=
    match p with
    | []        => m
    | ins :: p' =>
        let n' := n + inst_width ins in
        match ins with
        | (asm.Label lname, annot) =>
            let m' := symtable.add m lname (n, annot) in
            build_symtable n' m' p'
        | _ => build_symtable n' m p'
        end
    end.

(** [symtable_of_prog p] returns a symbol table with bindings from a
    string-label ASM program [p]. *)
Definition symtable_of_prog {A:Type} : @asm.annot_prog string A -> table A :=
    build_symtable 0 empty_table.


(** Instructions that have labels as targets (and require resolution). *)
Variant lbl_target_inst : Type := BEQ | BLT | J.

(** [lbl_target_inst_range ins] gives the closed interval of valid offset
    ranges corresponding to some instruction with a label target [ins]. *)
Definition lbl_target_inst_range (ins:lbl_target_inst) : Z * Z :=
    po2_signed_range match ins with
    | BEQ => 6
    | BLT => 6
    | J   => 16
    end.

(** [in_range_of_lbl_target_inst ins offest] is [true] when [offset] is within
    the valid offset range of label-targetting instruction [ins], and [false]
    otherwise. *)
Definition in_range_of_lbl_target_inst (ins:lbl_target_inst) (offset:Z)
    : bool :=
    let (lb, ub) := lbl_target_inst_range ins in
    Z.leb lb offset && Z.leb offset ub.


(** {2 Stage 1 --  Converting ASM programs to ISA programs} *)


(** [asm_inst_to_isa_insts tbl ins pc] represents the annotated ISA
    instructions generated by the translation of assembly instruction [ins], at
    program counter [pc], with the symbol table [tbl], and it is:
    - [Error e] if the conversion errors out with error [e:err A].
    - [Ok insts] if the operation succeeds and leads to annotated instructions
      [insts]. *)
Definition asm_inst_to_isa_insts {A:Type} (tbl:table A)
    (ins:@asm.annot_inst string A) (pc:nat)
    : result (list (@isa.annot_inst A)) (err A) :=
    let annot:A := asm.annot_of_annot_inst ins in   (* Annotation of [ins]. *)
    let oks v := Ok [v] in                          (* "Ok singleton". *)
    let isa_insts : result (list isa.inst) (err A) :=
    match asm.inst_of_annot_inst ins with
    | asm.Li rd n => oks (isa.Li rd n)
    | asm.Ld rd rs n => oks (isa.Ld rd rs n)
    | asm.St rd rs n => oks (isa.St rd rs n)
    | asm.Add rd rs1 rs2 => oks (isa.Add rd rs1 rs2)
    | asm.Addi rd rs n => oks (isa.Addi rd rs n)
    | asm.Sub rd rs1 rs2 => oks (isa.Sub rd rs1 rs2)
    | asm.And rd rs1 rs2 => oks (isa.And rd rs1 rs2)
    | asm.Not rd rs => oks (isa.Not rd rs)
    | asm.Sl rd rs n => oks (isa.Sl rd rs n)
    | asm.Sr rd rs n => oks (isa.Sr rd rs n)
    | asm.Beq rs1 rs2 l =>
        match symtable.find tbl l with
        | None                          => Error (UndefinedLabel l annot)
        | Some (symtable.Bindings x xs) =>
            match xs with
            | [] =>
                let target_pc:nat := fst x in
                let offset:Z := (Z.of_nat target_pc - Z.of_nat pc)%Z in
                if in_range_of_lbl_target_inst BEQ offset then
                    oks (isa.Beq rs1 rs2 (bv.of_Z offset _))
                else
                    Error (OOBBeq l annot offset)
            | _ => Error (DuplicateLabels l annot (x :: xs))
            end
        end
    | asm.Blt rs1 rs2 l =>
        match symtable.find tbl l with
        | None                          => Error (UndefinedLabel l annot)
        | Some (symtable.Bindings x xs) =>
            match xs with
            | [] =>
                let target_pc:nat := fst x in
                let offset:Z := (Z.of_nat target_pc - Z.of_nat pc)%Z in
                if in_range_of_lbl_target_inst BLT offset then
                    oks (isa.Blt rs1 rs2 (bv.of_Z offset _))
                else
                    Error (OOBBlt l annot offset)
            | _ => Error (DuplicateLabels l annot (x :: xs))
            end
        end
    | asm.Jalr rd rs n => oks (isa.Jalr rd rs n)
    | asm.Apc rd n => oks (isa.Apc rd n)
    | asm.J l =>
        match symtable.find tbl l with
        | None                          => Error (UndefinedLabel l annot)
        | Some (symtable.Bindings x xs) =>
            match xs with
            | [] =>
                let target_pc:nat := fst x in
                let offset:Z := (Z.of_nat target_pc - Z.of_nat pc)%Z in
                if in_range_of_lbl_target_inst J offset then
                    oks (isa.J (bv.of_Z offset _))
                else
                    Error (OOBJ l annot offset)
            | _ => Error (DuplicateLabels l annot (x :: xs))
            end
        end
    | asm.Label l => Ok []
    | asm.Spin => oks (isa.J (bv.of_Z 0 _))
    end in
    result_map (List.map (fun x => (x, annot))) isa_insts.

(** Helper function for [asm_prog_to_isa_prog] ([aptip] for short). *)
Fixpoint helper_aptip {A:Type} (p:@asm.annot_prog string A)
    (tbl:table A) (pc:nat)
    : result (@isa.annot_prog A) (err A) :=
    match p with
    | [] => Ok []
    | ins :: p' =>
        match asm_inst_to_isa_insts tbl ins pc with
        | Error e => Error e
        | Ok isa_insts =>
            match helper_aptip p' tbl (pc + inst_width ins) with
            | Error e => Error e
            | Ok isa_insts' => Ok (isa_insts ++ isa_insts')
            end
        end
    end.


(** [asm_prog_to_isa_prog p] represents the annotated ISA program corresponding
    to the annotated ASM program [p], and it is:
    - [Error e] if there is some error [e] in the translation.
    - [Ok p] if the translation is successful with output program [p]. *)
Definition asm_prog_to_isa_prog {A:Type} (p:@asm.annot_prog string A)
    : result (@isa.annot_prog A) (err A) :=
    let tbl:table A := symtable_of_prog p in
    helper_aptip p tbl 0.

Close Scope list.


(** {2 Stage 2 --  Converting ISA programs to machine programs} *)


Open Scope vector.

(** [opcode_of_isa_inst ins] returns the 16-bit opcode corresponding to
    annotated ISA instruction [ins]. *)
Definition opcode_of_isa_inst {A:Type} (ins:@isa.annot_inst A) : bv.t 16 :=
    let n:Z := Z.of_nat match isa.inst_of_annot_inst ins with
    | isa.Li _ _     => 1  | isa.Ld _ _ _   => 2  | isa.St _ _ _  => 3
    | isa.Add _ _ _  => 4  | isa.Addi _ _ _ => 5  | isa.Sub _ _ _ => 6
    | isa.And _ _ _  => 7  | isa.Not _ _    => 8  | isa.Sl _ _ _  => 9
    | isa.Sr _ _ _   => 10 | isa.Beq _ _ _  => 11 | isa.Blt _ _ _ => 12
    | isa.Jalr _ _ _ => 13 | isa.Apc _ _    => 14 | isa.J _       => 15
    end in
    bv.of_Z (2^(n - 1)) _.


(** [reg_to_bv r] is the length 5 bit-vector corresponding to [r]'s index. *)
Definition reg_to_bv (r:reg.t) : bv.t 5 := bv.of_Z (Z.of_nat (reg.index r)) _.

Definition isa_inst_to_machine_inst {A:Type} (ins:@isa.annot_inst A)
    : machine.t :=
    let r := reg_to_bv in               (** Shorthand for [reg_to_bv]   *)
    let zs (n:nat) := bv.of_Z 0%Z n in  (** Bit-vector with [n] zeroes. *)
    opcode_of_isa_inst ins ++
    match isa.inst_of_annot_inst ins with
    | isa.Li rd n        => r rd ++ n
    | isa.Ld rd rs n     => r rd ++ r rs ++ n
    | isa.St rd rs n     => r rd ++ r rs ++ n
    | isa.Add rd rs1 rs2 => r rd ++ r rs1 ++ r rs2 ++ zs 1
    | isa.Addi rd rs1 n  => r rd ++ r rs1 ++ n
    | isa.Sub rd rs1 rs2 => r rd ++ r rs1 ++ r rs2 ++ zs 1
    | isa.And rd rs1 rs2 => r rd ++ r rs1 ++ r rs2 ++ zs 1
    | isa.Not rd rs      => r rd ++ r rs ++ zs 6
    | isa.Sl rd rs n     => r rd ++ r rs ++ zs 1 ++ n
    | isa.Sr rd rs n     => r rd ++ r rs ++ zs 1 ++ n
    | isa.Beq rs1 rs2 n  => r rs1 ++ r rs2 ++ n
    | isa.Blt rs1 rs2 n  => r rs1 ++ r rs2 ++ n
    | isa.Jalr rd rs n   => r rd ++ r rs ++ n
    | isa.Apc rd n       => r rd ++ n
    | isa.J n            => n
    end.


(** [isa_prog_to_machine_prog p] converts annotated ISA program [p] to a
    machine program. *)
Definition isa_prog_to_machine_prog {A:Type}
    : @isa.annot_prog A -> machine.prog :=
    List.map isa_inst_to_machine_inst.


(** [assemble p] represents the assembly of annotated ASM program [p], and it
    is:
    - [Error e] in case the assembly has an error.
    - [Ok p] if the assembly is successful and the resultant machine program is
      [p]. *)
Definition assemble {A:Type} (p:@asm.annot_prog string A)
    : result machine.prog (err A) :=
    match asm_prog_to_isa_prog p with
    | Ok isa_prog => Ok (isa_prog_to_machine_prog isa_prog)
    | Error e     => Error e
    end.

