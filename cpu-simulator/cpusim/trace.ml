(*
    trace.ml

    Traces generated by instructions.
*)


module Ast = Syntax.Ast
open Ast

module Rf = Regfile
module RP = Types.Reg.Printers
module P = Types.Isa.Printers

(* Traces. *)
type t =
    | RegMod of Ram.word * Ast.t * Ast.reg * Ram.word
    | RamMod of Ram.word * Ast.t * Ram.addr * Ram.word
    | NoTrace of Ram.word * Ast.t

let to_string = function
    | RegMod (pc, inst, r, v) ->
            let rval = 
                match r with
                | Ast.R0 -> 0
                | _ -> v in
            let () = Printf.printf "(%04x)\t%s\n" pc (P.inst inst) in
            Printf.sprintf "\t%s\t%04x" (RP.reg r) rval
    | RamMod (pc, inst, addr, v) ->
            let () = Printf.printf "(%04x)\t%s\n" pc (P.inst inst) in
            Printf.sprintf "\t%04x\t%04x" addr v
    | NoTrace (pc, inst) ->
            let () = Printf.printf "(%04x)\t%s\n" pc (P.inst inst) in
            "\t-"

